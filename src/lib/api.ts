import fs from 'fs'
import { join } from 'path'
import matter from 'gray-matter'
import { AREAS } from './journeys'

const postsDirectory = join(process.cwd(), '_posts')

export function getPostSlugs() {
  return fs.readdirSync(postsDirectory, { withFileTypes: true })
}

type Items = {
  [key: string]: string
}

export function getPostBySlug(slug: string, fields: string[] = []) {
  const fullPath = join(postsDirectory, `${slug}/index.md`)
  const fileContents = fs.readFileSync(fullPath, 'utf8')
  const { data, content } = matter(fileContents)

  const items: Items = {}

  // Ensure only the minimal needed data is exposed
  fields.forEach((field) => {
    if (field === 'slug') {
      items[field] = slug
    }
    if (field === 'content') {
      items[field] = content
    }

    if (typeof data[field] !== 'undefined') {
      items[field] = data[field]
    }
  })

  return items
}

export function getAllPosts(fields: string[] = []) {
  const slugs = getPostSlugs()
  const posts = slugs
    .filter((item) => item.isDirectory())
    .map((slug) => getPostBySlug(slug.name, fields))
    // sort posts by date in descending order
    .sort((post1, post2) => (post1.date > post2.date ? -1 : 1))
  return posts
}

// Legacy title prefix, e.g. "[BD03] Criando o banco de dados".
const TITLE_PREFIX = /^\[.+?\d+\]\s*/

export function stripTitlePrefix(title: string) {
  return title.replace(TITLE_PREFIX, '')
}

// Pre-sized copies generated by scripts/thumbnails.mjs
export function coverVariant(coverImage: string, size: 'card' | 'wide') {
  return coverImage.replace(/cover\.\w+$/, `cover-${size}.webp`)
}

const WORDS_PER_MINUTE = 200

export function readingTime(markdown: string) {
  const words = markdown.split(/\s+/).filter(Boolean).length
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE))
}

export type PostJourney = {
  slug: string
  name: string
  areaKey: string
  areaName: string
  lesson: number
  total: number
}

export type PostSummary = {
  slug: string
  title: string
  shortTitle: string
  date: string
  excerpt: string
  categories: string[]
  cover: string
  wideCover: string
  readingTime: number
  journey: PostJourney | null
}

function findPostJourney(slug: string): PostJourney | null {
  for (const area of AREAS) {
    for (const journey of area.journeys) {
      const index = journey.lessons.indexOf(slug)
      if (index >= 0) {
        return {
          slug: journey.slug,
          name: journey.name,
          areaKey: area.key,
          areaName: area.name,
          lesson: index + 1,
          total: journey.lessons.length
        }
      }
    }
  }
  return null
}

export function getPostSummaries(): PostSummary[] {
  return getAllPosts([
    'slug',
    'title',
    'date',
    'excerpt',
    'categories',
    'coverImage',
    'content'
  ]).map((post) => ({
    slug: post.slug,
    title: post.title,
    shortTitle: stripTitlePrefix(post.title),
    date: post.date,
    excerpt: post.excerpt || '',
    categories: (post.categories as unknown as string[]) || [],
    cover: coverVariant(post.coverImage, 'card'),
    wideCover: coverVariant(post.coverImage, 'wide'),
    readingTime: readingTime(post.content || ''),
    journey: findPostJourney(post.slug)
  }))
}

export type Journey = {
  slug: string
  name: string
  description: string
  areaKey: string
  areaName: string
  lessons: PostSummary[]
  minutes: number
  next: { slug: string; name: string } | null
}

export type Area = {
  key: string
  name: string
  description: string
  journeys: Journey[]
}

export function getAreas(posts: PostSummary[]): Area[] {
  const allJourneys = AREAS.flatMap((area) => area.journeys)

  return AREAS.map((area) => ({
    key: area.key,
    name: area.name,
    description: area.description,
    journeys: area.journeys.map((journey) => {
      const lessons = journey.lessons.map((slug) => {
        const post = posts.find((item) => item.slug === slug)
        if (!post) {
          throw new Error(`Journey "${journey.slug}" lists unknown post "${slug}"`)
        }
        return post
      })
      const next = allJourneys.find((item) => item.slug === journey.next)

      return {
        slug: journey.slug,
        name: journey.name,
        description: journey.description,
        areaKey: area.key,
        areaName: area.name,
        lessons,
        minutes: lessons.reduce((total, post) => total + post.readingTime, 0),
        next: next ? { slug: next.slug, name: next.name } : null
      }
    })
  }))
}

export function getJourney(posts: PostSummary[], slug: string) {
  return getAreas(posts)
    .flatMap((area) => area.journeys)
    .find((journey) => journey.slug === slug)
}
