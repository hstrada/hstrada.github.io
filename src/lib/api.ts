import fs from 'fs'
import { join } from 'path'
import matter from 'gray-matter'

const postsDirectory = join(process.cwd(), '_posts')

export function getPostSlugs() {
  return fs.readdirSync(postsDirectory, { withFileTypes: true })
}

type Items = {
  [key: string]: string
}

export function getPostBySlug(slug: string, fields: string[] = []) {
  const fullPath = join(postsDirectory, `${slug}/index.md`)
  const fileContents = fs.readFileSync(fullPath, 'utf8')
  const { data, content } = matter(fileContents)

  const items: Items = {}

  // Ensure only the minimal needed data is exposed
  fields.forEach((field) => {
    if (field === 'slug') {
      items[field] = slug
    }
    if (field === 'content') {
      items[field] = content
    }

    if (typeof data[field] !== 'undefined') {
      items[field] = data[field]
    }
  })

  return items
}

export function getAllPosts(fields: string[] = []) {
  const slugs = getPostSlugs()
  const posts = slugs
    .filter((item) => item.isDirectory())
    .map((slug) => getPostBySlug(slug.name, fields))
    // sort posts by date in descending order
    .sort((post1, post2) => (post1.date > post2.date ? -1 : 1))
  return posts
}

export type Series = {
  key: string
  name: string
  count: number
  firstSlug: string
  categories: string[]
}

const SERIES_NAMES: { [key: string]: string } = {
  BD: 'Banco de Dados',
  BackEnd: 'BackEnd',
  'C#': 'C#',
  Kotlin: 'Kotlin'
}

// Titles like "[BD03] Criando o banco de dados" belong to the "BD" series.
const SERIES_PATTERN = /^\[(.+?)(\d+)\]\s*/

export type PostSeries = {
  key: string
  name: string
  number: number
}

export function parseSeries(title: string): PostSeries | null {
  const match = title?.match(SERIES_PATTERN)
  if (!match) return null

  return {
    key: match[1],
    name: SERIES_NAMES[match[1]] || match[1],
    number: Number(match[2])
  }
}

export function stripSeries(title: string) {
  return title.replace(SERIES_PATTERN, '')
}

// Pre-sized copies generated by scripts/thumbnails.mjs
export function coverVariant(coverImage: string, size: 'card' | 'wide') {
  return coverImage.replace(/cover\.\w+$/, `cover-${size}.webp`)
}

const WORDS_PER_MINUTE = 200

export function readingTime(markdown: string) {
  const words = markdown.split(/\s+/).filter(Boolean).length
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE))
}

export type PostSummary = {
  slug: string
  title: string
  shortTitle: string
  date: string
  excerpt: string
  categories: string[]
  cover: string
  wideCover: string
  readingTime: number
  series: PostSeries | null
}

export function getPostSummaries(): PostSummary[] {
  return getAllPosts([
    'slug',
    'title',
    'date',
    'excerpt',
    'categories',
    'coverImage',
    'content'
  ]).map((post) => ({
    slug: post.slug,
    title: post.title,
    shortTitle: stripSeries(post.title),
    date: post.date,
    excerpt: post.excerpt || '',
    categories: (post.categories as unknown as string[]) || [],
    cover: coverVariant(post.coverImage, 'card'),
    wideCover: coverVariant(post.coverImage, 'wide'),
    readingTime: readingTime(post.content || ''),
    series: parseSeries(post.title)
  }))
}

export function getSeriesPosts(posts: PostSummary[], key: string) {
  return posts
    .filter((post) => post.series?.key === key)
    .sort((a, b) => a.series.number - b.series.number)
}

type SeriesSource = { title: string; slug: string; categories?: unknown }

export function getSeries(allPosts: SeriesSource[]): Series[] {
  const series: { [key: string]: Series & { firstTitle: string } } = {}

  allPosts.forEach((post) => {
    const parsed = parseSeries(post.title)
    if (!parsed) return

    const { key } = parsed
    const current = series[key]
    const categories = (post.categories as unknown as string[]) || []

    if (!current) {
      series[key] = {
        key,
        name: parsed.name,
        count: 1,
        firstSlug: post.slug,
        firstTitle: post.title,
        categories: [...categories]
      }
      return
    }

    current.count += 1
    current.categories = [...new Set([...current.categories, ...categories])]
    if (post.title < current.firstTitle) {
      current.firstSlug = post.slug
      current.firstTitle = post.title
    }
  })

  return Object.values(series)
    .map(({ firstTitle, ...rest }) => rest)
    .sort((a, b) => b.count - a.count)
}
